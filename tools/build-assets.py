#!/usr/bin/env python3
"""Build optimised WebP derivatives + a JS manifest for the photo set.

Run:  python3 tools/build-assets.py
Out:  assets/img/opt/*.webp, js/photos.js, tools/contact/sheet-*.jpg
Originals in assets/img/ are never modified.
"""
import base64
import glob
import io
import json
import os
import re

from PIL import Image, ImageDraw, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "img")
OUT = os.path.join(SRC, "opt")
CONTACT = os.path.join(ROOT, "tools", "contact")

SIZES = {"tn": 400, "sm": 900, "md": 1700}
QUALITY = {"tn": 68, "sm": 72, "md": 76}


def build_one(path, num):
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    w, h = img.size
    entry = {"id": num, "w": w, "h": h, "ratio": round(w / h, 4), "src": {}}
    for key, target in SIZES.items():
        scale = min(1.0, target / w)
        resized = img.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
        name = f"kyz-{num}-{key}.webp"
        resized.save(os.path.join(OUT, name), "WEBP", quality=QUALITY[key], method=6)
        entry["src"][key] = f"assets/img/opt/{name}"
    blur = img.resize((20, max(1, round(20 * h / w))), Image.LANCZOS)
    buf = io.BytesIO()
    blur.save(buf, "WEBP", quality=35, method=4)
    entry["blur"] = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    entry["thumb"] = img.resize((320, round(320 * h / w)), Image.LANCZOS)
    return entry


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(CONTACT, exist_ok=True)
    files = sorted(glob.glob(os.path.join(SRC, "*.jpg")))
    entries = []
    for path in files:
        m = re.search(r"(\d{2})\.jpg$", path)
        if not m:
            continue
        entries.append(build_one(path, m.group(1)))

    payload = [
        {k: v for k, v in e.items() if k != "thumb"} for e in entries
    ]
    payload.sort(key=lambda e: e["id"])
    with open(os.path.join(ROOT, "js", "photos.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build-assets.py - data only, safe to edit captions in js/galleries.js */\n")
        fh.write("window.PHOTOS = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n")

    # contact sheets: 10 photos per sheet, numbered, for captioning
    per, cols = 10, 5
    for s in range(0, len(entries), per):
        chunk = entries[s:s + per]
        tw, th, pad, label = 300, 220, 8, 22
        rows = (len(chunk) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * (tw + pad) + pad, rows * (th + label + pad) + pad), (18, 18, 18))
        draw = ImageDraw.Draw(sheet)
        for i, e in enumerate(chunk):
            t = e["thumb"]
            t = ImageOps.fit(t, (tw, th), Image.LANCZOS)
            x = pad + (i % cols) * (tw + pad)
            y = pad + (i // cols) * (th + label + pad)
            sheet.paste(t, (x, y))
            draw.text((x + 4, y + th + 4), e["id"], fill=(255, 255, 255))
        n = s // per + 1
        sheet.save(os.path.join(CONTACT, f"sheet-{n}.jpg"), "JPEG", quality=82)
    print(f"{len(entries)} photos -> {OUT}, js/photos.js, contact sheets in {CONTACT}")


if __name__ == "__main__":
    main()
